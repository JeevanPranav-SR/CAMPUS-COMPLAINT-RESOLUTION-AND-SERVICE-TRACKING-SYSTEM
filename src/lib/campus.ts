export function getLocation(id: string) {
  return CAMPUS_LOCATIONS.find((item) => item.id === id);
}

export function nearestLocation(lat: number, lng: number) {
  return [...CAMPUS_LOCATIONS].sort((a, b) => {
    const da = (a.lat - lat) ** 2 + (a.lng - lng) ** 2;
    const db = (b.lat - lat) ** 2 + (b.lng - lng) ** 2;
    return da - db;
  })[0];
}

export function zoneColor(zone: CampusZone) {
  return CAMPUS_ZONES.find((item) => item.id === zone)?.color ?? "#22d3ee";
}
